const SQ_PATTERNS: [RegExp, (...groups: string[]) => string][] = [
  [/^You need (\d+) more tickets\.$/, (n) => `Të duhen edhe ${n} bileta.`],
  [/^This player only has (\d+) tickets\.$/, (n) => `Ky lojtar ka vetëm ${n} bileta.`],
  [/^This category contains (\d+) game\(s\)\. Choose how to proceed\.$/, (n) => `Kjo kategori ka ${n} lojë/lojëra. Zgjidh si të vazhdosh.`],
];

export function translateServerMessage(locale: Locale, message: string): string {
  if (locale === "en") return message;
  const exact = SQ[message];
  if (exact) return exact;
  for (const [pattern, build] of SQ_PATTERNS) {
    const match = message.match(pattern);
    if (match) return build(...match.slice(1));
  }
  return message;
}
